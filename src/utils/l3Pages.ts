// 线框图（docs/ui-wireframes-l3.html）里的「二级页」注册表 —— 数据层，不含任何 React。
//
// 为什么单独一个文件：线框图 23 屏里，①②③④⑪⑫⑬⑭ 这 8 屏在实现上原本只是"看用户/看自己/看机会"
// 主屏里的内联区块。审计（docs/ui-conformance-audit.md ⏳3）要求它们成为真正的独立全屏页，
// 并且每个页都要对用户讲清线框图写死的四件事：
//   解决什么问题 / 从哪进入 / 返回去哪 / 依赖哪些数据。
// 这四条**照抄线框图每个 <p class="note">** 的原文，集中放这里，页壳（L3Sheet）直接渲染，
// 测试（tests/l3Pages.test.ts）直接守——避免"页面做出来了但契约丢了"。
//
// 注意：本文件只放数据与纯函数，不放组件（组件在 src/components/L3Sheet.tsx）。

/** 已经落成独立 L3 页的 8 个二级页编号（线框图屏号） */
export type L3Id = '1' | '2' | '3' | '4' | '11' | '12' | '13' | '14';

/** 二级页归属的"看"（决定页头标签与信息条里的出处） */
export type L3Look = 'user' | 'market' | 'competitor' | 'self' | 'opportunity';

export const L3_LOOK_LABELS: Record<L3Look, string> = {
  user: '看用户',
  market: '看市场',
  competitor: '看竞对',
  self: '看自己',
  opportunity: '看机会',
};

export interface L3Page {
  id: L3Id;
  /** 线框图里的圈号 ①…⑭ */
  badge: string;
  look: L3Look;
  title: string;
  /** 解决什么问题（线框图 note 原文） */
  problem: string;
  /** 从哪进入（线框图 note 原文，与实现里的入口一一对应） */
  entry: string;
  /** 返回去哪（线框图 note 原文） */
  backTo: string;
  /** 依赖哪些数据（线框图 note 原文） */
  depends: string;
}


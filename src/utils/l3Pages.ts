/** 按编号取页（未知编号直接抛错：宁可在开发时报错，也不静默渲染一张空页） */
export function l3Page(id: L3Id): L3Page {
  const page = L3_PAGES.find((p) => p.id === id);
  if (!page) throw new Error(`未知的二级页编号：${String(id)}`);
  return page;
}
